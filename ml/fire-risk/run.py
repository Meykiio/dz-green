"""Kabylie test model (kabylie-v8): clean labels -> honest test -> 2027 grid.

Research record only. The app's map comes from the national model
(run_national.py), which replaced this one on 2026-11-08.

    python run.py
"""
import json
from fire_risk import config as C
from fire_risk.evaluate import forward_test, summarize
from fire_risk.features import training_table
from fire_risk.labels import build_labels, load_points
from fire_risk.model import fit, importance
from fire_risk.score import load_grid, score_grid


def pct(x: float) -> str:
    return f"{round(x * 100)}%"


def report_md(metrics: dict) -> str:
    s, lab, grid = metrics["test"], metrics["labels"], metrics["grid"]
    lines = [
        f"# Fire-risk model {C.MODEL_VERSION}: results",
        "",
        "Generated by `python run.py`. Do not edit by hand.",
        "",
        "## Labels",
        f"- Raw satellite fire detections: {lab['raw_fire_detections']}",
        f"- Dropped as permanent heat sources (factory/dump pattern): {lab['dropped_persistent_heat_sources']} "
        f"in {lab['persistent_cells']} cells",
        f"- Dropped as built-up land: {lab['dropped_built_up_only']}",
        f"- Clean fire events (one per ~1 km cell per year): {lab['clean_fire_events']}",
        f"- Random land sample: {lab['random_land_points']}",
        "",
        "## Honest test",
        "Each year predicted by a model trained only on earlier years, graded against random land.",
        "",
        "| Year | Fires | AUC | Top 10% of land holds | Top 20% | Top 30% |",
        "|---|---|---|---|---|---|",
    ]
    for r in s["per_year"]:
        lines.append(f"| {r['year']} | {r['fires']} | {r['auc']:.3f} | {pct(r['top10'])} of fires | "
                     f"{pct(r['top20'])} | {pct(r['top30'])} |")
    m, w = s["mean"], s["worst_year"]
    lines += [
        f"| **Mean** | | **{m['auc']:.3f}** | **{pct(m['top10'])}** | **{pct(m['top20'])}** | **{pct(m['top30'])}** |",
        f"| Worst year | | {w['auc']:.3f} | {pct(w['top10'])} | {pct(w['top20'])} | {pct(w['top30'])} |",
        "",
        "Random guessing would give 10% / 20% / 30%.",
        "",
        "## What the final model relies on (share of gain)",
    ]
    lines += [f"- {k}: {pct(v)}" for k, v in metrics["importance"].items()]
    lines += [
        "",
        f"## {C.TARGET_YEAR} map",
        f"- Grid cells: {grid['grid_cells']}, dropped water/built-up: {grid['dropped_not_burnable']}, "
        f"published: {grid['scored_cells']}",
        "- Published value is a relative rank (share of mapped land that is less risky), not a probability.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    points = load_points()
    events, land, label_report = build_labels(points)
    print(f"labels: {label_report['clean_fire_events']} clean fire events "
          f"({label_report['dropped_persistent_heat_sources']} persistent-source detections dropped)")

    per_year = forward_test(events, land)
    summary = summarize(per_year)
    print(per_year.round(3).to_string(index=False))
    print("mean:", summary["mean"], "worst:", summary["worst_year"])

    final = fit(training_table(events, land, before_year=C.TARGET_YEAR))
    cells, grid_report = score_grid(final, load_grid(), events)

    metrics = {"model_version": C.MODEL_VERSION, "target_year": C.TARGET_YEAR,
               "features": C.FEATURES, "params": C.MODEL_PARAMS, "labels": label_report,
               "test": summary, "importance": importance(final), "grid": grid_report}
    C.RESULTS.mkdir(exist_ok=True)
    (C.RESULTS / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    (C.RESULTS / "report.md").write_text(report_md(metrics), encoding="utf-8")
    cells.round(5).to_csv(C.RESULTS / f"grid_{C.TARGET_YEAR}_scored.csv", index=False)


if __name__ == "__main__":
    main()
