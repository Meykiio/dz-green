"""Plain-language results page (results/national/report.md)."""
from . import config as C


def pct(x: float) -> str:
    return f"{round(x * 100)}%"


def _row(label: str, r: dict) -> str:
    return (
        f"| {label} | {r.get('burned_cells', '')} | {r['auc']:.3f} | {r['auc_rule']:.3f} | "
        f"{pct(r['top10'])} | {pct(r['top10_rule'])} | {pct(r['top20'])} | "
        f"{pct(r['top20_rule'])} | {pct(r['top20_detections'])} |"
    )


def report_md(m: dict) -> str:
    t, lab = m["test"], m["labels"]
    lines = [
        f"# National fire-risk model {C.MODEL_VERSION}: results",
        "",
        "Generated by `python run_national.py`. Do not edit by hand.",
        "",
        "## Data",
        f"- NASA FIRMS MODIS detections, northern Algeria ({C.LAT_MIN} N and up), {C.FIRST_YEAR}-2025",
        f"- Excluded as industrial heat: {lab['static_source_detections']} static-source detections "
        f"({lab['excluded_cells_static']} cells) and {lab['excluded_cells_persistent']} persistent cells",
        f"- Land grid: {m['grid_cells']} cells of 2 x 2 km",
        "",
        "## Honest test",
        f"Each year is predicted using only data up to {C.GAP} years earlier (the {C.TARGET_YEAR} "
        "map uses data to 2025), and graded on every land cell. 'Rule' ranks land by recent "
        "fires nearby, with no model.",
        "",
        "| Year | Burned cells | AUC | AUC rule | Top 10% of land holds | Rule | Top 20% | Rule "
        "| Top 20%, weighted by detections |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    lines += [_row(str(r["year"]), r) for r in t["per_year"]]
    lines += [_row("**Mean**", t["mean"]), _row("Worst", t["worst_year"])]
    lines += [
        "",
        "Random guessing: the top 10% of land holds 10% of fires, the top 20% holds 20%.",
        "",
        "## What the model relies on (share of gain)",
    ]
    ranked = sorted(m["importance"].items(), key=lambda kv: -kv[1])
    lines += [f"- {k}: {pct(v)}" for k, v in ranked]
    return "\n".join(lines) + "\n"
